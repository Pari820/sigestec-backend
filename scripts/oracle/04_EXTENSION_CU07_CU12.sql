CREATE TABLE APROBACION_ATS (
    id_aprobacion_ats NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_analisis_trabajo_seguro NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    fecha_revision DATE NOT NULL,
    supervisor_cliente VARCHAR2(300) NOT NULL,
    ssoma_cliente VARCHAR2(300) NOT NULL,
    resultado VARCHAR2(20) NOT NULL,
    observaciones VARCHAR2(1000),
    url_acta VARCHAR2(1000),
    CONSTRAINT uq_aprobacion_ats UNIQUE (id_analisis_trabajo_seguro),
    CONSTRAINT ck_aprobacion_resultado CHECK (resultado IN ('APROBADO','RECHAZADO')),
    CONSTRAINT fk_aprobacion_ats FOREIGN KEY (id_analisis_trabajo_seguro) REFERENCES ANALISIS_TRABAJO_SEGURO(id_analisis_trabajo_seguro),
    CONSTRAINT fk_aprobacion_empleado FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE EJECUCION_SERVICIO (
    id_ejecucion_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_trabajo NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    fecha_ejecucion TIMESTAMP NOT NULL,
    descripcion VARCHAR2(1500) NOT NULL,
    mediciones VARCHAR2(1500),
    observaciones VARCHAR2(1500),
    estado VARCHAR2(30) NOT NULL,
    CONSTRAINT uq_ejecucion_ot UNIQUE (id_orden_trabajo),
    CONSTRAINT fk_ejecucion_ot FOREIGN KEY (id_orden_trabajo) REFERENCES ORDEN_TRABAJO(id_orden_trabajo),
    CONSTRAINT fk_ejecucion_empleado FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE EVIDENCIA_EJECUCION (
    id_evidencia_ejecucion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion_servicio NUMBER NOT NULL,
    etapa VARCHAR2(20) NOT NULL,
    url_archivo VARCHAR2(1000) NOT NULL,
    nombre_archivo VARCHAR2(250),
    CONSTRAINT ck_evidencia_etapa CHECK (etapa IN ('ANTES','DURANTE','DESPUES')),
    CONSTRAINT fk_evidencia_ejec FOREIGN KEY (id_ejecucion_servicio) REFERENCES EJECUCION_SERVICIO(id_ejecucion_servicio)
);

CREATE TABLE MATERIAL (
    id_material NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(30) NOT NULL,
    nombre VARCHAR2(180) NOT NULL,
    unidad_medida VARCHAR2(30) NOT NULL,
    stock_actual NUMBER(12,2) NOT NULL,
    stock_minimo NUMBER(12,2) NOT NULL,
    estado VARCHAR2(1) NOT NULL,
    CONSTRAINT uq_material_codigo UNIQUE (codigo),
    CONSTRAINT ck_material_stock CHECK (stock_actual >= 0 AND stock_minimo >= 0)
);

CREATE TABLE MATERIAL_UTILIZADO (
    id_material_utilizado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion_servicio NUMBER NOT NULL,
    id_material NUMBER NOT NULL,
    cantidad_real NUMBER(12,2) NOT NULL,
    estado_validacion VARCHAR2(25) NOT NULL,
    CONSTRAINT ck_material_real CHECK (cantidad_real > 0),
    CONSTRAINT fk_material_uso_ejec FOREIGN KEY (id_ejecucion_servicio) REFERENCES EJECUCION_SERVICIO(id_ejecucion_servicio),
    CONSTRAINT fk_material_uso_material FOREIGN KEY (id_material) REFERENCES MATERIAL(id_material)
);

CREATE TABLE INFORME_TECNICO (
    id_informe_tecnico NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_trabajo NUMBER NOT NULL,
    id_ejecucion_servicio NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    numero_informe VARCHAR2(40),
    fecha_informe DATE NOT NULL,
    fecha_envio DATE NOT NULL,
    diagnostico VARCHAR2(1500) NOT NULL,
    trabajos_realizados VARCHAR2(2000) NOT NULL,
    conclusiones VARCHAR2(1500) NOT NULL,
    recomendaciones VARCHAR2(1500),
    url_archivo VARCHAR2(1000),
    estado VARCHAR2(25) NOT NULL,
    CONSTRAINT uq_informe_ot UNIQUE (id_orden_trabajo),
    CONSTRAINT uq_informe_numero UNIQUE (numero_informe),
    CONSTRAINT fk_informe_ot FOREIGN KEY (id_orden_trabajo) REFERENCES ORDEN_TRABAJO(id_orden_trabajo),
    CONSTRAINT fk_informe_ejec FOREIGN KEY (id_ejecucion_servicio) REFERENCES EJECUCION_SERVICIO(id_ejecucion_servicio),
    CONSTRAINT fk_informe_empleado FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE EVIDENCIA_INFORME_TECNICO (
    id_evidencia_informe_tecnico NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_informe_tecnico NUMBER NOT NULL,
    url_archivo VARCHAR2(1000) NOT NULL,
    nombre_archivo VARCHAR2(250),
    CONSTRAINT fk_evidencia_informe FOREIGN KEY (id_informe_tecnico) REFERENCES INFORME_TECNICO(id_informe_tecnico)
);

CREATE TABLE CONFORMIDAD_SERVICIO (
    id_conformidad_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_trabajo NUMBER NOT NULL,
    id_informe_tecnico NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    id_representante_empresa NUMBER,
    nombre_representante VARCHAR2(250) NOT NULL,
    numero_acta VARCHAR2(50) NOT NULL,
    fecha_conformidad DATE NOT NULL,
    valoracion NUMBER NOT NULL,
    observaciones VARCHAR2(1000),
    estado_conformidad VARCHAR2(30) NOT NULL,
    url_archivo VARCHAR2(1000) NOT NULL,
    CONSTRAINT uq_conformidad_ot UNIQUE (id_orden_trabajo),
    CONSTRAINT uq_conformidad_acta UNIQUE (numero_acta),
    CONSTRAINT ck_conformidad_valor CHECK (valoracion BETWEEN 1 AND 5),
    CONSTRAINT ck_conformidad_estado CHECK (estado_conformidad IN ('CONFORME','OBSERVADA')),
    CONSTRAINT fk_conformidad_ot FOREIGN KEY (id_orden_trabajo) REFERENCES ORDEN_TRABAJO(id_orden_trabajo),
    CONSTRAINT fk_conformidad_informe FOREIGN KEY (id_informe_tecnico) REFERENCES INFORME_TECNICO(id_informe_tecnico),
    CONSTRAINT fk_conformidad_empleado FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado),
    CONSTRAINT fk_conformidad_rep FOREIGN KEY (id_representante_empresa) REFERENCES REPRESENTANTE_EMPRESA(id_representante)
);

CREATE TABLE MOVIMIENTO_MATERIAL_ALMACEN (
    id_movimiento_material_almacen NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_material NUMBER NOT NULL,
    id_orden_trabajo NUMBER,
    id_empleado_registra NUMBER NOT NULL,
    tipo_movimiento VARCHAR2(20) NOT NULL,
    cantidad NUMBER(12,2) NOT NULL,
    fecha_movimiento TIMESTAMP NOT NULL,
    motivo VARCHAR2(400),
    observacion VARCHAR2(1000),
    CONSTRAINT ck_mov_material_tipo CHECK (tipo_movimiento IN ('ENTRADA','SALIDA','DEVOLUCION')),
    CONSTRAINT ck_mov_material_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_mov_material_material FOREIGN KEY (id_material) REFERENCES MATERIAL(id_material),
    CONSTRAINT fk_mov_material_ot FOREIGN KEY (id_orden_trabajo) REFERENCES ORDEN_TRABAJO(id_orden_trabajo),
    CONSTRAINT fk_mov_material_empleado FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE MOVIMIENTO_HERRAMIENTA_EQUIPO (
    id_movimiento_herramienta_equipo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_herramienta_equipo NUMBER NOT NULL,
    id_orden_trabajo NUMBER,
    id_empleado_registra NUMBER NOT NULL,
    id_empleado_responsable NUMBER,
    tipo_movimiento VARCHAR2(20) NOT NULL,
    cantidad NUMBER(12,2) NOT NULL,
    fecha_movimiento TIMESTAMP NOT NULL,
    estado_devolucion VARCHAR2(20),
    observacion VARCHAR2(1000),
    CONSTRAINT ck_mov_herr_tipo CHECK (tipo_movimiento IN ('INGRESO','PRESTAMO','DEVOLUCION')),
    CONSTRAINT ck_mov_herr_estado CHECK (estado_devolucion IS NULL OR estado_devolucion IN ('BUENO','DANADO')),
    CONSTRAINT ck_mov_herr_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_mov_herr_herr FOREIGN KEY (id_herramienta_equipo) REFERENCES HERRAMIENTA_EQUIPO(id_herramienta_equipo),
    CONSTRAINT fk_mov_herr_ot FOREIGN KEY (id_orden_trabajo) REFERENCES ORDEN_TRABAJO(id_orden_trabajo),
    CONSTRAINT fk_mov_herr_registra FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado),
    CONSTRAINT fk_mov_herr_resp FOREIGN KEY (id_empleado_responsable) REFERENCES EMPLEADO(id_empleado)
);

CREATE INDEX ix_mat_uso_ejec ON MATERIAL_UTILIZADO(id_ejecucion_servicio);
CREATE INDEX ix_mov_mat_ot ON MOVIMIENTO_MATERIAL_ALMACEN(id_orden_trabajo,id_material);
CREATE INDEX ix_mov_herr_ot ON MOVIMIENTO_HERRAMIENTA_EQUIPO(id_orden_trabajo,id_herramienta_equipo);
COMMIT;
