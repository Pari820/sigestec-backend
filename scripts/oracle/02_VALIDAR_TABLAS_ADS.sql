-- Verificación de columnas del esquema ADS existente (no modifica nada).
SELECT table_name, COUNT(*) AS columnas FROM user_tab_columns
WHERE table_name IN ('PERFIL', 'PERSONA_NATURAL', 'PERSONA_JURIDICA', 'CARGO', 'EMPLEADO', 'TECNICO', 'REPRESENTANTE_EMPRESA', 'TIPO_SERVICIO', 'USUARIO', 'ROL', 'USUARIO_ROL', 'SOLICITUD_SERVICIO', 'COTIZACION', 'DETALLE_COTIZACION', 'ORDEN_COMPRA', 'DETALLE_ORDEN_COMPRA', 'ORDEN_TRABAJO', 'ASIGNACION_PERSONAL', 'DOCUMENTO_PLANIFICACION', 'ANALISIS_TRABAJO_SEGURO', 'RIESGO', 'DETALLE_ANALISIS_RIESGO', 'EQUIPO_PROTECCION_PERSONAL', 'ANALISIS_EQUIPO_PROTECCION_PERSONAL', 'HERRAMIENTA_EQUIPO', 'ANALISIS_HERRAMIENTA_EQUIPO')
GROUP BY table_name ORDER BY table_name;

SELECT table_name, column_name, data_type, nullable FROM user_tab_columns
WHERE table_name IN ('COTIZACION','DETALLE_COTIZACION','ORDEN_COMPRA','DETALLE_ORDEN_COMPRA',
'ORDEN_TRABAJO','ASIGNACION_PERSONAL','DOCUMENTO_PLANIFICACION','ANALISIS_TRABAJO_SEGURO',
'DETALLE_ANALISIS_RIESGO','ANALISIS_EQUIPO_PROTECCION_PERSONAL','ANALISIS_HERRAMIENTA_EQUIPO')
ORDER BY table_name, column_id;

SELECT table_name, constraint_name, constraint_type, status FROM user_constraints
WHERE table_name IN ('COTIZACION','ORDEN_COMPRA','ORDEN_TRABAJO','ANALISIS_TRABAJO_SEGURO')
ORDER BY table_name, constraint_type;
