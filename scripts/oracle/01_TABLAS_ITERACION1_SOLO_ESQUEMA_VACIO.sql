CREATE TABLE PERFIL (
    id_perfil NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_perfil VARCHAR2(10) NOT NULL,
    estado CHAR(1),
    fecha_registro TIMESTAMP
);

CREATE TABLE PERSONA_NATURAL (
    id_persona_natural NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_perfil NUMBER NOT NULL,
    dni VARCHAR2(8),
    nombres VARCHAR2(100) NOT NULL,
    apellidos VARCHAR2(120) NOT NULL,
    telefono VARCHAR2(20),
    correo VARCHAR2(150),
    estado CHAR(1),
    CONSTRAINT uq_persona_natura_1 UNIQUE (id_perfil),
    CONSTRAINT uq_persona_natura_2 UNIQUE (dni),
    CONSTRAINT fk_persona_natura_1 FOREIGN KEY (id_perfil) REFERENCES PERFIL(id_perfil)
);

CREATE TABLE PERSONA_JURIDICA (
    id_persona_juridica NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_perfil NUMBER NOT NULL,
    ruc VARCHAR2(11) NOT NULL,
    razon_social VARCHAR2(180) NOT NULL,
    direccion VARCHAR2(250),
    telefono VARCHAR2(20),
    correo VARCHAR2(150),
    estado CHAR(1),
    CONSTRAINT uq_persona_juridi_1 UNIQUE (id_perfil),
    CONSTRAINT uq_persona_juridi_2 UNIQUE (ruc),
    CONSTRAINT fk_persona_juridi_1 FOREIGN KEY (id_perfil) REFERENCES PERFIL(id_perfil)
);

CREATE TABLE CARGO (
    id_cargo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(80) NOT NULL,
    descripcion VARCHAR2(1000),
    estado CHAR(1),
    CONSTRAINT uq_cargo_1 UNIQUE (nombre)
);

CREATE TABLE EMPLEADO (
    id_empleado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_natural NUMBER NOT NULL,
    id_cargo NUMBER NOT NULL,
    codigo_empleado VARCHAR2(20) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    estado CHAR(1),
    CONSTRAINT uq_empleado_1 UNIQUE (id_persona_natural),
    CONSTRAINT uq_empleado_2 UNIQUE (codigo_empleado),
    CONSTRAINT fk_empleado_1 FOREIGN KEY (id_persona_natural) REFERENCES PERSONA_NATURAL(id_persona_natural),
    CONSTRAINT fk_empleado_2 FOREIGN KEY (id_cargo) REFERENCES CARGO(id_cargo)
);

CREATE TABLE TECNICO (
    id_tecnico NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado NUMBER NOT NULL,
    estado CHAR(1),
    CONSTRAINT uq_tecnico_1 UNIQUE (id_empleado),
    CONSTRAINT fk_tecnico_1 FOREIGN KEY (id_empleado) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE REPRESENTANTE_EMPRESA (
    id_representante NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_natural NUMBER NOT NULL,
    id_persona_juridica NUMBER NOT NULL,
    cargo_representante VARCHAR2(120),
    tipo_representante VARCHAR2(30),
    estado CHAR(1),
    CONSTRAINT fk_representante__1 FOREIGN KEY (id_persona_natural) REFERENCES PERSONA_NATURAL(id_persona_natural),
    CONSTRAINT fk_representante__2 FOREIGN KEY (id_persona_juridica) REFERENCES PERSONA_JURIDICA(id_persona_juridica)
);

CREATE TABLE TIPO_SERVICIO (
    id_tipo_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    descripcion VARCHAR2(1000),
    estado CHAR(1),
    CONSTRAINT uq_tipo_servicio_1 UNIQUE (nombre)
);

CREATE TABLE USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_natural NUMBER NOT NULL,
    nombre_usuario VARCHAR2(60) NOT NULL,
    clave_hash VARCHAR2(255) NOT NULL,
    estado CHAR(1),
    fecha_creacion TIMESTAMP,
    CONSTRAINT uq_usuario_1 UNIQUE (id_persona_natural),
    CONSTRAINT uq_usuario_2 UNIQUE (nombre_usuario),
    CONSTRAINT fk_usuario_1 FOREIGN KEY (id_persona_natural) REFERENCES PERSONA_NATURAL(id_persona_natural)
);

CREATE TABLE ROL (
    id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    descripcion VARCHAR2(1000),
    estado CHAR(1),
    CONSTRAINT uq_rol_1 UNIQUE (nombre)
);

CREATE TABLE USUARIO_ROL (
    id_usuario_rol NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL,
    id_rol NUMBER NOT NULL,
    CONSTRAINT fk_usuario_rol_1 FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario),
    CONSTRAINT fk_usuario_rol_2 FOREIGN KEY (id_rol) REFERENCES ROL(id_rol)
);

CREATE TABLE SOLICITUD_SERVICIO (
    id_solicitud NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_juridica NUMBER NOT NULL,
    id_representante_solicitante NUMBER,
    id_empleado_registra NUMBER NOT NULL,
    id_tipo_servicio NUMBER NOT NULL,
    fecha_solicitud DATE NOT NULL,
    fecha_requerida DATE,
    descripcion VARCHAR2(1000) NOT NULL,
    lugar_servicio VARCHAR2(300),
    observaciones VARCHAR2(1000),
    prioridad VARCHAR2(255) NOT NULL,
    estado VARCHAR2(20) NOT NULL,
    url_archivo_adjunto VARCHAR2(1000),
    CONSTRAINT fk_solicitud_serv_1 FOREIGN KEY (id_persona_juridica) REFERENCES PERSONA_JURIDICA(id_persona_juridica),
    CONSTRAINT fk_solicitud_serv_2 FOREIGN KEY (id_representante_solicitante) REFERENCES REPRESENTANTE_EMPRESA(id_representante),
    CONSTRAINT fk_solicitud_serv_3 FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado),
    CONSTRAINT fk_solicitud_serv_4 FOREIGN KEY (id_tipo_servicio) REFERENCES TIPO_SERVICIO(id_tipo_servicio)
);

CREATE TABLE COTIZACION (
    id_cotizacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud NUMBER NOT NULL,
    id_persona_juridica NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    id_representante_respuesta NUMBER,
    numero_cotizacion VARCHAR2(30) NOT NULL,
    fecha_emision DATE NOT NULL,
    fecha_vencimiento DATE,
    fecha_respuesta DATE,
    subtotal NUMBER(12,2) NOT NULL,
    igv NUMBER(12,2) NOT NULL,
    total NUMBER(12,2) NOT NULL,
    estado VARCHAR2(20) NOT NULL,
    observaciones VARCHAR2(1000),
    url_archivo VARCHAR2(1000),
    CONSTRAINT uq_cotizacion_1 UNIQUE (numero_cotizacion),
    CONSTRAINT fk_cotizacion_1 FOREIGN KEY (id_solicitud) REFERENCES SOLICITUD_SERVICIO(id_solicitud),
    CONSTRAINT fk_cotizacion_2 FOREIGN KEY (id_persona_juridica) REFERENCES PERSONA_JURIDICA(id_persona_juridica),
    CONSTRAINT fk_cotizacion_3 FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado),
    CONSTRAINT fk_cotizacion_4 FOREIGN KEY (id_representante_respuesta) REFERENCES REPRESENTANTE_EMPRESA(id_representante)
);

CREATE TABLE DETALLE_COTIZACION (
    id_detalle_cotizacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cotizacion NUMBER NOT NULL,
    item NUMBER(6) NOT NULL,
    descripcion VARCHAR2(500) NOT NULL,
    cantidad NUMBER(12,2) NOT NULL,
    unidad_medida VARCHAR2(30),
    precio_unitario NUMBER(12,2) NOT NULL,
    subtotal NUMBER(12,2) NOT NULL,
    CONSTRAINT uq_detalle_cotiza_1 UNIQUE (id_cotizacion, item),
    CONSTRAINT fk_detalle_cotiza_1 FOREIGN KEY (id_cotizacion) REFERENCES COTIZACION(id_cotizacion)
);

CREATE TABLE ORDEN_COMPRA (
    id_orden_compra NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cotizacion NUMBER NOT NULL,
    id_persona_juridica NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    id_representante_emisor NUMBER,
    numero_orden_compra VARCHAR2(40) NOT NULL,
    fecha_emision DATE NOT NULL,
    monto_total NUMBER(12,2) NOT NULL,
    url_archivo VARCHAR2(1000),
    estado VARCHAR2(20),
    CONSTRAINT uq_orden_compra_1 UNIQUE (id_cotizacion),
    CONSTRAINT uq_orden_compra_2 UNIQUE (numero_orden_compra),
    CONSTRAINT fk_orden_compra_1 FOREIGN KEY (id_cotizacion) REFERENCES COTIZACION(id_cotizacion),
    CONSTRAINT fk_orden_compra_2 FOREIGN KEY (id_persona_juridica) REFERENCES PERSONA_JURIDICA(id_persona_juridica),
    CONSTRAINT fk_orden_compra_3 FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado),
    CONSTRAINT fk_orden_compra_4 FOREIGN KEY (id_representante_emisor) REFERENCES REPRESENTANTE_EMPRESA(id_representante)
);

CREATE TABLE DETALLE_ORDEN_COMPRA (
    id_detalle_orden_compra NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra NUMBER NOT NULL,
    item NUMBER(6) NOT NULL,
    descripcion VARCHAR2(500) NOT NULL,
    cantidad NUMBER(12,2) NOT NULL,
    unidad_medida VARCHAR2(30),
    precio_unitario NUMBER(12,2),
    subtotal NUMBER(12,2),
    CONSTRAINT uq_detalle_orden__1 UNIQUE (id_orden_compra, item),
    CONSTRAINT fk_detalle_orden__1 FOREIGN KEY (id_orden_compra) REFERENCES ORDEN_COMPRA(id_orden_compra)
);

CREATE TABLE ORDEN_TRABAJO (
    id_orden_trabajo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra NUMBER NOT NULL,
    id_persona_juridica NUMBER NOT NULL,
    id_empleado_registra NUMBER NOT NULL,
    numero_orden_trabajo VARCHAR2(30) NOT NULL,
    fecha_programada_inicio TIMESTAMP,
    fecha_programada_fin TIMESTAMP,
    fecha_coordinacion_cliente TIMESTAMP,
    lugar_trabajo VARCHAR2(300),
    descripcion VARCHAR2(1000),
    estado VARCHAR2(25) NOT NULL,
    CONSTRAINT uq_orden_trabajo_1 UNIQUE (id_orden_compra),
    CONSTRAINT uq_orden_trabajo_2 UNIQUE (numero_orden_trabajo),
    CONSTRAINT fk_orden_trabajo_1 FOREIGN KEY (id_orden_compra) REFERENCES ORDEN_COMPRA(id_orden_compra),
    CONSTRAINT fk_orden_trabajo_2 FOREIGN KEY (id_persona_juridica) REFERENCES PERSONA_JURIDICA(id_persona_juridica),
    CONSTRAINT fk_orden_trabajo_3 FOREIGN KEY (id_empleado_registra) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE ASIGNACION_PERSONAL (
    id_asignacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_trabajo NUMBER NOT NULL,
