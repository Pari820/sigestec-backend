    CONSTRAINT fk_asignacion_per_1 FOREIGN KEY (id_orden_trabajo) REFERENCES ORDEN_TRABAJO(id_orden_trabajo),
    CONSTRAINT fk_asignacion_per_2 FOREIGN KEY (id_empleado) REFERENCES EMPLEADO(id_empleado)
);

CREATE TABLE DOCUMENTO_PLANIFICACION (
